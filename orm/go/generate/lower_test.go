// The committed example is a real Go package, so `go build ./...` type-checks
// everything the query generator emits.
const (
	exampleQueryDir = "../examples/queries"
	exampleModelDir = "../examples/generated/models"
	exampleOutDir   = "../examples/generated/vorm/gen"
)

func TestGeneratedQueryExampleIsUpToDate(t *testing.T) {
	dir := t.TempDir()
	res, err := Run(&Options{
		QueryDir: exampleQueryDir,
		ModelDir: exampleModelDir,
		OutDir:   dir,
		Package:  "gen",
		Dialect:  "postgres",
		Driver:   "pgx",
	})
	if err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(dir, "queries_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	// Keep the sample header pointing at the example path.
	body := strings.Replace(string(got),
		"// Models table structs: vorm generate models (DO NOT EDIT models/).",
		"// Sample path: examples/generated/ — real apps use ./vorm/gen/queries_gen.go",
		1)

	golden := filepath.Join(exampleOutDir, "queries_gen.go")
	if *updateGolden {
		if err := os.WriteFile(golden, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("updated %s (%d queries, %d runtime-only)", golden, res.Queries, len(res.Pending))
		return
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("%s missing (run: go test ./generate -update): %v", golden, err)
	}
	if string(want) != body {
		t.Errorf("%s drifted from the generator (run: go test ./generate -update)", golden)
	}
}

// userModel is the model package the stub fixtures resolve against.
const userModel = `// Code generated by vorm generate models; DO NOT EDIT.
package models

import (
	"github.com/vorzela/vorm"
	"github.com/vorzela/vorm/query"
)

type User struct {
	vorm.Model
	Email  string ` + "`json:\"email\" db:\"email\"`" + `
	Name   string ` + "`json:\"name\" db:\"name\"`" + `
	Active bool   ` + "`json:\"active\" db:\"active\"`" + `
	Age    int    ` + "`json:\"age\" db:\"age\"`" + `
}

var Users = query.Model[User](query.Meta{
	Table: "users",
	Columns: []string{
		"id", "email", "name", "active", "age",
		"created_at", "updated_at", "deleted_at",
	},
	SoftDeletes: true,
})
`

// lower runs the generator over a single stub body and returns the source of
// the emitted function.
func lower(t *testing.T, dialect, stubBody string) string {
	t.Helper()
	root := t.TempDir()
	qdir := filepath.Join(root, "queries")
	mdir := filepath.Join(root, "models")
	outdir := filepath.Join(root, "gen")
	for _, d := range []string{qdir, mdir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(mdir, "user.go"), []byte(userModel), 0o644); err != nil {
		t.Fatal(err)
	}
	src := "package queries\n\nimport (\n\t\"context\"\n\n\t\"github.com/vorzela/vorm/query\"\n)\n\n" + stubBody
	if err := os.WriteFile(filepath.Join(qdir, "q.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Run(&Options{
		QueryDir: qdir, OutDir: outdir, ModelDir: mdir,
		Package: "gen", Dialect: dialect, Driver: "pgx",
	}); err != nil {
		t.Fatalf("generate: %v", err)
	}
	body, err := os.ReadFile(filepath.Join(outdir, "queries_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	return string(body)
}

func wants(t *testing.T, src string, want ...string) {
	t.Helper()
	for _, w := range want {
		if !strings.Contains(src, w) {
			t.Errorf("missing %q in:\n%s", w, src)
		}
	}
}

func TestLowerJoinsGroupByAndHaving(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=TopAuthors
func TopAuthors(ctx context.Context, db query.DB) ([]User, error) {
	return Users.New().
		Join("posts", "posts.user_id = users.id").
		Select("id", "email").
		Where("active", true).
		GroupBy("id").
		Having("age", ">", 1).
		OrderByDesc("email").
		Get(ctx, db)
}
`)
	wants(t, src,
		`INNER JOIN "posts" ON posts.user_id = users.id`,
		`SELECT "users"."id", "users"."email"`,
		`WHERE "users"."active" = $1`,
		`GROUP BY "users"."id"`,
		`HAVING "users"."age" > $2`,
		`ORDER BY "users"."email" DESC`,
	)
}

func TestLowerDynamicInBindsEveryElement(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=ByIDs
func ByIDs(ctx context.Context, db query.DB, ids ...any) ([]User, error) {
	return Users.Where("active", true).WhereIn("id", ids...).OrderBy("id").Get(ctx, db)
}
`)
	wants(t, src,
		"Ids []any",
		"args := make([]any, 0, 1+len(arg.Ids))",
		"query.InClause(query.DialectPostgres, `\"id\"`, len(args)+1, len(arg.Ids))",
		"for _, v := range arg.Ids {",
		"db.QueryContext(ctx, sb.String(), args...)",
	)
}

// A placeholder after a dynamic IN group cannot be numbered at generate time,
// because the group's width is only known once the slice arrives.
func TestLowerNumbersPlaceholdersAfterDynamicIn(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=ByIDsPaged
func ByIDsPaged(ctx context.Context, db query.DB, limit int, ids ...any) ([]User, error) {
	return Users.WhereIn("id", ids...).Limit(limit).Get(ctx, db)
}
`)
	wants(t, src,
		"sb.WriteString(query.Placeholder(query.DialectPostgres, len(args)+1))",
		"args = append(args, arg.Limit)",
	)
}

func TestLowerFixedInStaysConst(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=ByAges
func ByAges(ctx context.Context, db query.DB) ([]User, error) {
	return Users.WhereIn("age", 18, 21).Get(ctx, db)
}
`)
	wants(t, src, `"age" IN ($1, $2)`, "db.QueryContext(ctx, byAgesSQL, 18, 21)")
	if strings.Contains(src, "strings.Builder") {
		t.Errorf("a fixed IN list must stay a const statement:\n%s", src)
	}
}

func TestLowerSearchBindsPatternPerColumn(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=Search
func Search(ctx context.Context, db query.DB, q string, limit int) ([]User, error) {
	return Users.WhereSearch([]string{"name", "email"}, q).Limit(limit).Get(ctx, db)
}
`)
	wants(t, src,
		`("name" ILIKE $1 OR "email" ILIKE $2)`,
		"LIMIT $3",
		// The escaped pattern is built once and bound to both columns.
		"pattern1 := query.LikePattern(arg.Q)",
		"db.QueryContext(ctx, searchSQL, pattern1, pattern1, arg.Limit)",
	)
}

