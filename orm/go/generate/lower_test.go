func TestLowerCountAndExists(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=CountActive
func CountActive(ctx context.Context, db query.DB) (int64, error) {
	return Users.Where("active", true).Count(ctx, db)
}

// vorm:query name=HasEmail
func HasEmail(ctx context.Context, db query.DB, email string) (bool, error) {
	return Users.Where("email", email).Exists(ctx, db)
}
`)
	wants(t, src,
		`SELECT COUNT(*) FROM "users" WHERE "active" = $1 AND "deleted_at" IS NULL`,
		"func CountActive(ctx context.Context, db query.DB) (int64, error)",
		`SELECT 1 FROM "users" WHERE "email" = $1 AND "deleted_at" IS NULL LIMIT 1`,
		"func HasEmail(ctx context.Context, db query.DB, arg HasEmailParams) (bool, error)",
		"if query.IsNotFound(err) {",
	)
}

func TestLowerPaginateBindsLimitAndCounts(t *testing.T) {
	src := lower(t, "postgres", `
// vorm:query name=Page
func Page(ctx context.Context, db query.DB, page, perPage int) (*query.PageResult[User], error) {
	return Users.Where("active", true).OrderBy("id").OffsetPage(ctx, db, page, perPage)
}
`)
	wants(t, src,
		"(*query.PageResult[PageRow], error)",
		"LIMIT $2 OFFSET $3",
		"perPage, (page-1)*perPage",
		"SELECT COUNT(*)",
		"pages = int((total + int64(perPage) - 1) / int64(perPage))",
	)
	if strings.Contains(src, "ORDER BY \"id\" ASC LIMIT $2 OFFSET $3`\n\tvar total") {
		t.Error("the COUNT statement must not carry ORDER BY/LIMIT")
	}
}

