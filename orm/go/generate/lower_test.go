func TestLowerRejectsUnknownColumn(t *testing.T) {
	root := t.TempDir()
	qdir := filepath.Join(root, "queries")
	mdir := filepath.Join(root, "models")
	for _, d := range []string{qdir, mdir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(mdir, "user.go"), []byte(userModel), 0o644); err != nil {
		t.Fatal(err)
	}
	stub := `package queries

import (
	"context"

	"github.com/vorzela/vorm/query"
)

// vorm:query name=Bad
func Bad(ctx context.Context, db query.DB) ([]User, error) {
	return Users.Where("nope", 1).Get(ctx, db)
}
`
	if err := os.WriteFile(filepath.Join(qdir, "q.go"), []byte(stub), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := Run(&Options{QueryDir: qdir, OutDir: filepath.Join(root, "gen"), ModelDir: mdir, Dialect: "postgres"})
	if err == nil {
		t.Fatal("expected an unknown-column failure at generate time")
	}
	if !strings.Contains(err.Error(), "nope") {
		t.Fatalf("error should name the column: %v", err)
	}
}

func TestLowerReportsRuntimeOnlyStubs(t *testing.T) {
	root := t.TempDir()
	qdir := filepath.Join(root, "queries")
	mdir := filepath.Join(root, "models")
	for _, d := range []string{qdir, mdir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(mdir, "user.go"), []byte(userModel), 0o644); err != nil {
		t.Fatal(err)
	}
	stub := `package queries

import (
	"context"

	"github.com/vorzela/vorm/query"
)

// vorm:query name=Eager
func Eager(ctx context.Context, db query.DB) ([]User, error) {
	return Users.Where("active", true).With("posts").Get(ctx, db)
}
`
	if err := os.WriteFile(filepath.Join(qdir, "q.go"), []byte(stub), 0o644); err != nil {
		t.Fatal(err)
	}
	res, err := Run(&Options{QueryDir: qdir, OutDir: filepath.Join(root, "gen"), ModelDir: mdir, Dialect: "postgres"})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Pending) != 1 || res.Pending[0].Name != "Eager" {
		t.Fatalf("Pending = %+v", res.Pending)
	}
	if !strings.Contains(res.Pending[0].Reason, "eager loading") {
		t.Fatalf("reason should explain why: %q", res.Pending[0].Reason)
	}
}
